"""Build the browser-only course bundles: data.js, data-c.js, data-html.js.

The hosted site is fully static and never runs Python — this script is a
*build-time* helper only. It reads the same content modules the dev server
uses, and writes one JavaScript file per course containing everything
(Python: 31 chapters; C: 13 chapters; HTML: 13 chapters). The web app then
needs no backend at all.

Usage:
    python build_static.py          # write static/data.js + data-c.js
    python build_static.py --check  # validate content, exit without writing
"""

import json
import os
import sys

import content    # assembles + validates the Python course (imports diagrams)
import ctutor_content  # assembles + validates the C course
import html_content   # assembles + validates the HTML course
import css_content    # assembles + validates the CSS course
import js_content     # assembles + validates the JS course


OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "static", "data.js")
OUT_C = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "static", "data-c.js")
OUT_HTML = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "static", "data-html.js")
OUT_CSS = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "static", "data-css.js")
OUT_JS = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "static", "data-js.js")


def to_js(chapters):
    """Serialize the course to a JS snippet (JSON with `</` escaped)."""
    payload = json.dumps(
        {"chapters": chapters}, ensure_ascii=False, separators=(",", ":"))
    # `\/` is a valid JSON escape; replacing `</` keeps the bundle from
    # ever being able to close the <script> tag it is embedded in.
    payload = payload.replace("</", "<\\/")
    return ("/* Auto-generated by build_static.py - do not edit. */\n"
            "/* Regenerate with: python build_static.py */\n"
            "window.COURSE_DATA = " + payload + ";\n")


