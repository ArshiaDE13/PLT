def write_bundle(path, js, parsed_chapters, label):
    start = js.index("{")
    end = js.rindex("};") + 1
    parsed = json.loads(js[start:end].replace("<\\/", "</"))
    if len(parsed["chapters"]) != len(parsed_chapters):
        raise SystemExit("round-trip check failed for " + label)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(js)
    print("wrote %s (%.1f KB, %d chapters)"
          % (path, os.path.getsize(path) / 1024.0, len(parsed_chapters)))


def main():
    content.validate()      # crashes loudly on malformed content
    ctutor_content.validate()
    html_content.validate()
    css_content.validate()
    js_content.validate()
    n_lessons = sum(len(c["lessons"]) for c in content.CHAPTERS)
    n_quiz = sum(len(c["quiz"]) for c in content.CHAPTERS)
    c_lessons = sum(len(c["lessons"]) for c in ctutor_content.CHAPTERS)
    c_quiz = sum(len(c["quiz"]) for c in ctutor_content.CHAPTERS)
    h_lessons = sum(len(c["lessons"]) for c in html_content.CHAPTERS)
    h_quiz = sum(len(c["quiz"]) for c in html_content.CHAPTERS)
    s_lessons = sum(len(c["lessons"]) for c in css_content.CHAPTERS)
    s_quiz = sum(len(c["quiz"]) for c in css_content.CHAPTERS)
    j_lessons = sum(len(c["lessons"]) for c in js_content.CHAPTERS)
    j_quiz = sum(len(c["quiz"]) for c in js_content.CHAPTERS)
    if "--check" in sys.argv[1:]:
        print("content OK: python %d chapters, %d lessons, %d quiz questions"
              % (len(content.CHAPTERS), n_lessons, n_quiz))
        print("content OK: c %d chapters, %d lessons, %d quiz questions"
              % (len(ctutor_content.CHAPTERS), c_lessons, c_quiz))
        print("content OK: html %d chapters, %d lessons, %d quiz questions"
              % (len(html_content.CHAPTERS), h_lessons, h_quiz))
        print("content OK: css %d chapters, %d lessons, %d quiz questions"
              % (len(css_content.CHAPTERS), s_lessons, s_quiz))
        print("content OK: js %d chapters, %d lessons, %d quiz questions"
              % (len(js_content.CHAPTERS), j_lessons, j_quiz))
        return 0

    # build_content() replaces [[diag:...]] placeholders with inline SVG and
    # attaches Persian variants; the C/HTML/CSS builders attach Persian.
    write_bundle(OUT, to_js(content.build_content()),
                 content.CHAPTERS, "python")
    write_bundle(OUT_C, to_js_c(ctutor_content.build_content()),
                 ctutor_content.CHAPTERS, "c")
    write_bundle(OUT_HTML, to_js_html(html_content.build_content()),
                 html_content.CHAPTERS, "html")
    write_bundle(OUT_CSS, to_js_css(css_content.build_content()),
                 css_content.CHAPTERS, "css")
    write_bundle(OUT_JS, to_js_js(js_content.build_content()),
                 js_content.CHAPTERS, "js")
    return 0


if __name__ == "__main__":
    sys.exit(main())